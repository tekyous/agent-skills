#!/usr/bin/env python3
"""Copy the Tekyous MCP server's design_stack prompt into the skill, so the two never drift.

    python3 scripts/sync_design_stack.py           # rewrite plugins/tekyous/skills/tech-stack-diagram/references/design-stack.md
    python3 scripts/sync_design_stack.py --check   # exit 1 if the copy differs from the live prompt (CI)

The prompt is the one source for how to write a good diagram spec. Agents with the MCP connected read it from the
server; the skill carries this copy for agents without it.
"""

from __future__ import annotations

import json
import sys
import urllib.request
from pathlib import Path

ENDPOINT = "https://mcp.tekyous.dev/mcp?src=ci"
TARGET = Path(__file__).resolve().parents[1] / "plugins" / "tekyous" / "skills" / "tech-stack-diagram" / "references" / "design-stack.md"
MARKER = "@@REQUEST@@"
HEADER = (
    "<!-- Generated by scripts/sync_design_stack.py from the design_stack prompt of the Tekyous MCP server. "
    "Do not edit by hand: the prompt is the one source. -->\n\n"
    "# How to write a good tech stack diagram spec\n\n"
    "The same guidance the Tekyous MCP server gives in its `design_stack` prompt. Without the MCP connected, "
    "\"call compose_diagram\" and \"search_tools\" mean the curl calls in SKILL.md.\n\n"
)


def live_prompt() -> str:
    body = json.dumps({"jsonrpc": "2.0", "id": 1, "method": "prompts/get",
                       "params": {"name": "design_stack", "arguments": {"request": MARKER}}}).encode()
    req = urllib.request.Request(ENDPOINT, data=body, method="POST", headers={
        "Content-Type": "application/json",
        "Accept": "application/json, text/event-stream",
        # Cloudflare answers Python's default User-Agent with 403 (error 1010)
        "User-Agent": "tekyous-skill-sync/1",
    })
    with urllib.request.urlopen(req, timeout=30) as r:
        text = json.load(r)["result"]["messages"][0]["content"]["text"]
    # The prompt ends with "The request: <request>"; the skill has no request to fill in
    head, sep, _ = text.rpartition(MARKER)
    if not sep:
        raise SystemExit("The prompt no longer ends with the request; update this script.")
    return head.rstrip().removesuffix("The request:").rstrip() + "\n"


def main() -> int:
    expected = HEADER + live_prompt()
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
    if "--check" in sys.argv:
        if current != expected:
            print(f"{TARGET.name} differs from the live design_stack prompt: run scripts/sync_design_stack.py")
            return 1
        print(f"{TARGET.name} matches the live prompt.")
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(expected, encoding="utf-8")
    print(f"{'Updated' if current != expected else 'Unchanged:'} {TARGET.relative_to(TARGET.parents[5])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
